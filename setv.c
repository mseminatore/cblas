//------------------------------------------------------
void cblas_ssetv(CBLAS_INDEX n, float *x, float v)
{
	for (CBLAS_INDEX i = 0; i < n; i++)
		*x++ = v;
}

//------------------------------------------------------
//
//------------------------------------------------------
void cblas_dsetv(CBLAS_INDEX n, double *x, double v)
{
	for (CBLAS_INDEX i = 0; i < n; i++)
		*x++ = v;
}